"""启动 8 个 tmux 角色窗口，并写入讨论开场消息。"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
WORKSPACE = ROOT
CONFIG = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))
WSL_ROOT = "/mnt/c/Users/30209/Desktop/Agora"
WSL_PLATFORM = WSL_ROOT
SESSION = CONFIG.get("tmux_session", "arch")


def wsl(*args: str, input_text: str | None = None, check: bool = False) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["wsl", "-e", *args],
        input=input_text,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=check,
    )


def write_env() -> None:
    names = [
        "ANTHROPIC_BASE_URL",
        "ANTHROPIC_AUTH_TOKEN",
        "ANTHROPIC_MODEL",
        "ANTHROPIC_DEFAULT_OPUS_MODEL",
        "ANTHROPIC_DEFAULT_SONNET_MODEL",
        "ANTHROPIC_DEFAULT_HAIKU_MODEL",
        "CLAUDE_CODE_MAX_CONTEXT_TOKENS",
        "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC",
    ]
    lines = ["# generated by start_discussion.py; do not commit"]
    for name in names:
        value = os.environ.get(name)
        if value:
            lines.append(f"export {name}={shlex.quote(value)}")
    content = "\n".join(lines) + "\n"
    proc = wsl("sh", "-c", "umask 077; cat > ~/.kirke-discussion-env", input_text=content)
    if proc.returncode != 0:
        raise SystemExit(f"write env failed: {proc.stderr}")
    print("[start] env written to ~/.kirke-discussion-env")


def tmux(*args: str) -> subprocess.CompletedProcess:
    return wsl("tmux", *args)


def stop() -> None:
    tmux("kill-session", "-t", SESSION)
    print(f"[start] stopped {SESSION}")


def start() -> None:
    write_env()
    stop()
    import bus
    bus.set_paused(False)
    roles = CONFIG["roles"]
    first = roles[0]
    proc = tmux(
        "new-session",
        "-d",
        "-s",
        SESSION,
        "-n",
        first["id"],
        "-c",
        WSL_PLATFORM,
        f"python3 role_loop.py {first['id']}",
    )
    if proc.returncode != 0:
        raise SystemExit(proc.stderr)
    for role in roles[1:]:
        proc = tmux(
            "new-window",
            "-t",
            SESSION,
            "-n",
            role["id"],
            "-c",
            WSL_PLATFORM,
            f"python3 role_loop.py {role['id']}",
        )
        if proc.returncode != 0:
            raise SystemExit(proc.stderr)
    # 角色需要先启动并记录 last_seq，再发开场，避免被当成历史消息跳过。
    time.sleep(6)
    import bus

    topic_path = WORKSPACE / "topic.md"
    topic = topic_path.read_text(encoding="utf-8").strip() if topic_path.exists() else "请围绕当前主题展开讨论。"
    bus.append(
        "moderator",
        f"讨论开始。主题：{topic}\n"
        "每个角色按自己的立场发言；有值得推进的提案，输出 propose，id 带上你的角色 id；"
        "评估者独立投票 yes/no/blocked；没有新论点就输出 pass。",
        "system",
        "主持人",
    )
    print(f"[start] {len(roles)} roles running in tmux session {SESSION}")
    print(f"[start] attach: wsl -e tmux attach -t {SESSION}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["start", "stop"], nargs="?", default="start")
    args = parser.parse_args()
    if args.command == "stop":
        stop()
    else:
        start()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
